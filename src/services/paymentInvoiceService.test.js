import assert from 'node:assert/strict'
import test from 'node:test'
import {
  createAutoPaymentInvoice,
  ensurePaymentsHaveAutoInvoices,
  normalizeClinicalRecordPayments,
  paymentDocumentNeedsRenumber,
  reserveNextPaymentDocumentNumber,
} from './paymentInvoiceService.ts'

test('el recibo de caja interno no reserva un número de factura FV', () => {
  const recibo = createAutoPaymentInvoice({
    paymentDate: '2026-10-27',
    amount: 200000,
    paymentReason: 'Exodoncia de dientes permanentes',
    documentKind: 'recibo_interno',
  })
  const factura = createAutoPaymentInvoice({
    paymentDate: '2026-10-27',
    amount: 200000,
    documentKind: 'factura',
  })

  assert.match(recibo.invoiceNumber, /^RC\d{8}$/)
  assert.equal(recibo.documentKind, 'recibo_interno')
  assert.match(factura.invoiceNumber, /^FV\d{8}$/)
  assert.equal(factura.documentKind, 'factura')
  assert.doesNotMatch(recibo.notes ?? '', /factura electrónica de venta/i)
})

test('los recibos legados con prefijo FV se renumeran a RC sin colisionar', () => {
  const normalized = ensurePaymentsHaveAutoInvoices([
    {
      id: 'p1',
      paymentDate: '2026-11-01',
      amount: 100000,
      paymentMethod: 'contado',
      paymentReason: 'Limpieza',
      documentKind: 'recibo_interno',
      invoices: [
        {
          id: 'i1',
          invoiceNumber: 'FV00000001',
          invoiceDate: '2026-11-01',
          amount: 100000,
          autoGenerated: true,
          emissionMode: 'manual',
        },
      ],
    },
    {
      id: 'p2',
      paymentDate: '2026-11-02',
      amount: 150000,
      paymentMethod: 'contado',
      paymentReason: 'Resina',
      documentKind: 'recibo_interno',
      invoices: [
        {
          id: 'i2',
          invoiceNumber: 'FV00000001',
          invoiceDate: '2026-11-02',
          amount: 150000,
          autoGenerated: true,
          emissionMode: 'manual',
          notes: 'Recibo de caja interno — sin factura electrónica',
        },
      ],
    },
  ])

  assert.match(normalized[0].invoices[0].invoiceNumber, /^RC\d{8}$/)
  assert.match(normalized[1].invoices[0].invoiceNumber, /^RC\d{8}$/)
  assert.notEqual(
    normalized[0].invoices[0].invoiceNumber,
    normalized[1].invoices[0].invoiceNumber,
  )
  assert.equal(normalized[0].invoices[0].documentKind, 'recibo_interno')
  assert.equal(normalized[1].documentKind, 'recibo_interno')
})

test('FV queda reservado a facturas reales y no se duplica el mismo consecutivo', () => {
  const normalized = normalizeClinicalRecordPayments({
    paymentControl: [
      {
        id: 'f1',
        paymentDate: '2026-11-03',
        amount: 200000,
        paymentMethod: 'contado',
        paymentReason: 'FEV',
        documentKind: 'factura',
        invoices: [
          {
            id: 'fi1',
            invoiceNumber: 'FV00000001',
            invoiceDate: '2026-11-03',
            amount: 200000,
            autoGenerated: true,
            emissionMode: 'provider',
            cufe: 'CUFE-1',
            documentKind: 'factura',
          },
        ],
      },
      {
        id: 'f2',
        paymentDate: '2026-11-04',
        amount: 250000,
        paymentMethod: 'contado',
        paymentReason: 'FEV duplicada',
        documentKind: 'factura',
        invoices: [
          {
            id: 'fi2',
            invoiceNumber: 'FV00000001',
            invoiceDate: '2026-11-04',
            amount: 250000,
            autoGenerated: true,
            emissionMode: 'provider',
            cufe: 'CUFE-2',
          },
        ],
      },
    ],
    orthodonticsPaymentControl: [],
  })

  assert.equal(normalized.paymentControl[0].invoices[0].invoiceNumber, 'FV00000001')
  assert.match(normalized.paymentControl[1].invoices[0].invoiceNumber, /^FV\d{8}$/)
  assert.notEqual(
    normalized.paymentControl[1].invoices[0].invoiceNumber,
    'FV00000001',
  )
})

test('paymentDocumentNeedsRenumber detecta prefijo incorrecto por tipo', () => {
  assert.equal(paymentDocumentNeedsRenumber('FV00000001', 'recibo_interno'), true)
  assert.equal(paymentDocumentNeedsRenumber('RC00000001', 'recibo_interno'), false)
  assert.equal(paymentDocumentNeedsRenumber('FV00000002', 'factura'), false)
  assert.equal(paymentDocumentNeedsRenumber('RC00000002', 'factura'), true)
})

test('reserveNextPaymentDocumentNumber evita números ya usados', () => {
  const used = new Set(['RC00000001', 'RC00000002'])
  const next = reserveNextPaymentDocumentNumber(undefined, 'recibo_interno', used)
  assert.match(next, /^RC\d{8}$/)
  assert.ok(!used.has(next))
  assert.notEqual(next, 'RC00000001')
  assert.notEqual(next, 'RC00000002')
})
