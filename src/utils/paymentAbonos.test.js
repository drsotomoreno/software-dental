import assert from 'node:assert/strict'
import test from 'node:test'
import {
  abonoFitsBalance,
  abonoHistoryForLine,
  documentKindFromEmission,
  parseAbonoAmount,
  paymentReceiptActionLabel,
  procedurePaymentStatus,
  remainingAfterAbono,
  resolvePaymentDocumentKind,
} from './paymentAbonos.ts'

test('el monto del abono se escribe a mano y no toma el saldo completo', () => {
  assert.equal(parseAbonoAmount(''), 0)
  assert.equal(parseAbonoAmount('50.000'), 50000)
  assert.equal(abonoFitsBalance(50000, 200000), true)
  assert.equal(abonoFitsBalance(200000, 200000), true)
  assert.equal(abonoFitsBalance(200001, 200000), false)
  assert.equal(remainingAfterAbono(200000, 50000), 150000)
})

test('el historial descuenta cada abono y conserva saldo y tipo de comprobante', () => {
  const history = abonoHistoryForLine('line-1', 200000, [
    {
      id: 'p1',
      paymentControlLineId: 'line-1',
      paymentDate: '2026-10-01',
      amount: 50000,
      paymentMethod: 'contado',
      paymentReason: 'Resina',
      documentKind: 'recibo_interno',
      remainingBalance: 150000,
      invoices: [
        {
          id: 'i1',
          invoiceNumber: 'RC1',
          invoiceDate: '2026-10-01',
          amount: 50000,
          emissionMode: 'manual',
          autoGenerated: true,
        },
      ],
    },
    {
      id: 'otro',
      paymentControlLineId: 'line-2',
      paymentDate: '2026-10-02',
      amount: 999,
      paymentMethod: 'contado',
      paymentReason: 'Otro',
      invoices: [],
    },
    {
      id: 'p2',
      paymentControlLineId: 'line-1',
      paymentDate: '2026-10-03',
      amount: 150000,
      paymentMethod: 'contado',
      paymentReason: 'Resina',
      documentKind: 'factura',
      remainingBalance: 0,
      invoices: [
        {
          id: 'i2',
          invoiceNumber: 'FV1',
          invoiceDate: '2026-10-03',
          amount: 150000,
          emissionMode: 'provider',
          autoGenerated: true,
        },
      ],
    },
  ])

  assert.equal(history.length, 2)
  assert.equal(history[0].appliedAmount, 50000)
  assert.equal(history[0].remainingBalance, 150000)
  assert.equal(history[0].documentKind, 'recibo_interno')
  assert.equal(history[1].remainingBalance, 0)
  assert.equal(history[1].documentKind, 'factura')
  assert.equal(paymentReceiptActionLabel(history[0].documentKind), 'Ver Recibo')
  assert.equal(paymentReceiptActionLabel(history[1].documentKind), 'Ver Factura')
  assert.equal(procedurePaymentStatus(0, 200000).label, 'Pagado')
  assert.equal(procedurePaymentStatus(150000, 50000).tone, 'due')
})

test('un comprobante antiguo sin tipo usa la etiqueta genérica', () => {
  const kind = resolvePaymentDocumentKind({
    id: 'legacy',
    paymentDate: '2026-01-01',
    amount: 10000,
    paymentMethod: 'contado',
    paymentReason: 'Control',
    invoices: [
      {
        id: 'inv',
        invoiceNumber: 'FV0001',
        invoiceDate: '2026-01-01',
        amount: 10000,
        autoGenerated: true,
      },
    ],
  })
  assert.equal(kind, null)
  assert.equal(paymentReceiptActionLabel(kind), 'Ver Recibo / Factura')
  assert.equal(documentKindFromEmission('factura', 'manual'), 'recibo_interno')
  assert.equal(documentKindFromEmission('factura', 'provider'), 'factura')
})

test('un mismo recibo abona solo la parte de cada procedimiento', () => {
  const history = abonoHistoryForLine('resina', 150000, [
    {
      id: 'paquete',
      paymentDate: '2026-10-26',
      amount: 280000,
      paymentMethod: 'contado',
      paymentReason: 'Consulta · Resina · Profilaxis',
      documentKind: 'recibo_interno',
      invoices: [],
      lineAllocations: [
        { lineId: 'consulta', amount: 50000, description: 'Consulta', cupsCode: '890201' },
        { lineId: 'resina', amount: 150000, description: 'Resina', cupsCode: '232101' },
        { lineId: 'profilaxis', amount: 80000, description: 'Profilaxis', cupsCode: '997103' },
      ],
    },
  ])
  assert.equal(history.length, 1)
  assert.equal(history[0].appliedAmount, 150000)
  assert.equal(history[0].remainingBalance, 0)
  assert.equal(history[0].payment.amount, 280000)
})
